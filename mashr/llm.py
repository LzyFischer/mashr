"""Chat sampling (Tinker, or a local vLLM server for MASHR_LOCAL_MODELS) with per-call thinking budgets
and a persistent sqlite cache.

A call is keyed by (model, messages, thinking, max_tokens, seed); replaying a run with an unchanged
prompt costs nothing and returns the identical reply, so harness edits only pay for calls whose
input actually changed.
"""
import hashlib
import json
import os
import sqlite3
import threading
import time
from collections import defaultdict
from dataclasses import dataclass

THINK_BUDGET = {"off": 0, "low": 1024, "medium": 2048, "high": 4096, "xhigh": 8192, "max": 16384}
# local serving: models listed in MASHR_LOCAL_MODELS are sampled from the vLLM server at MASHR_LOCAL
# (OpenAI completions API, token ids in and out) instead of Tinker; their calls are cached separately
LOCAL_URL = os.environ.get("MASHR_LOCAL", "http://localhost:8001/v1")
LOCAL_MODELS = set(filter(None, os.environ.get("MASHR_LOCAL_MODELS", "").split(",")))
CACHE_PATH = os.environ.get("MASHR_CACHE", os.path.join(os.path.dirname(__file__), "..",
                                                        "results", "cache", "cache.sqlite"))


@dataclass
class Reply:
    text: str            # visible answer (reasoning stripped)
    prompt_tokens: int
    gen_tokens: int      # reasoning + answer tokens
    cached: bool


class LLM:
    def __init__(self, cache_path: str = CACHE_PATH):
        os.makedirs(os.path.dirname(cache_path), exist_ok=True)
        self._db = sqlite3.connect(cache_path, check_same_thread=False)
        self._db.execute("CREATE TABLE IF NOT EXISTS c (k TEXT PRIMARY KEY, v TEXT)")
        self._db.commit()
        self._lock = threading.Lock()
        self._inflight: dict = {}      # key -> Event: identical concurrent calls sample once
        self._clients: dict = {}
        self._service = None
        # per model: calls, cache hits, recorded tokens of sampled calls, and tokens actually sent to
        # / generated by the sampler (billed; includes the re-prefill of budget-forced continuations)
        self.usage = defaultdict(lambda: dict.fromkeys(
            ("calls", "cached", "prompt", "gen", "billed_prompt", "billed_gen"), 0))

    def snapshot(self) -> dict:
        with self._lock:
            return {m: dict(u) for m, u in self.usage.items()}

    def _count(self, model, **kv):
        with self._lock:
            u = self.usage[model]
            for k, v in kv.items():
                u[k] += v

    def _local_tok(self, model):
        with self._lock:
            if ("tok", model) not in self._clients:
                from transformers import AutoTokenizer
                self._clients[("tok", model)] = AutoTokenizer.from_pretrained(model)
            return self._clients[("tok", model)]

    def _local_sample(self, model, prompt_ids, n, temperature, seed, stops):
        import urllib.request
        body = json.dumps({"model": model, "prompt": prompt_ids, "max_tokens": n,
                           "temperature": temperature, "seed": seed, "stop": stops,
                           "skip_special_tokens": False, "return_token_ids": True}).encode()
        req = urllib.request.Request(f"{LOCAL_URL}/completions", data=body,
                                     headers={"Content-Type": "application/json"})
        with urllib.request.urlopen(req, timeout=3600) as r:
            ch = json.load(r)["choices"][0]
        return list(ch["token_ids"])

    def _client(self, model: str):
        import tinker
        with self._lock:
            if self._service is None:
                self._service = tinker.ServiceClient()
            if model not in self._clients:
                s = self._service.create_sampling_client(base_model=model)
                self._clients[model] = (s, s.get_tokenizer())
            return self._clients[model]

    def chat(self, model: str, messages: list[dict], thinking: str = "off", max_tokens: int = 1024,
             seed: int = 0, temperature: float = 0.6) -> Reply:
        # thinking calls carry a sampler version: v2 fixed answers truncated by the shared budget
        ver = ([] if thinking == "off" else ["v2"]) + (["local"] if model in LOCAL_MODELS else [])
        key = hashlib.sha256(json.dumps([model, messages, thinking, max_tokens, seed, temperature]
                                        + ver, sort_keys=True).encode()).hexdigest()
        while True:
            with self._lock:
                row = self._db.execute("SELECT v FROM c WHERE k=?", (key,)).fetchone()
                if row:
                    d = json.loads(row[0])
                    u = self.usage[model]
                    u["calls"] += 1
                    u["cached"] += 1
                    return Reply(d["text"], d["prompt_tokens"], d["gen_tokens"], True)
                ev = self._inflight.get(key)
                if ev is None:
                    self._inflight[key] = threading.Event()
                    break
            ev.wait()                  # another thread is sampling this exact call; reuse it
        try:
            text, pt, gt = self._sample(model, messages, thinking, max_tokens, seed, temperature)
            self._count(model, calls=1, prompt=pt, gen=gt)
            with self._lock:
                self._db.execute("INSERT OR REPLACE INTO c VALUES (?,?)", (key, json.dumps(
                    {"text": text, "prompt_tokens": pt, "gen_tokens": gt})))
                self._db.commit()
        finally:
            with self._lock:
                self._inflight.pop(key).set()
        return Reply(text, pt, gt, False)

    def _sample(self, model, messages, thinking, max_tokens, seed, temperature):
        local = model in LOCAL_MODELS
        if local:
            samp, tok = None, self._local_tok(model)
        else:
            from tinker import types
            samp, tok = self._client(model)
        think = thinking != "off"
        ids = tok.apply_chat_template(messages, add_generation_prompt=True, tokenize=True,
                                      enable_thinking=think)
        ids = list(ids["input_ids"] if hasattr(ids, "keys") else ids)
        stops = [tok.eos_token, "<|im_end|>"]

        def sample(prompt_ids, n):
            for attempt in range(5):
                try:
                    if local:
                        out = self._local_sample(model, prompt_ids, n, temperature, seed, stops)
                    else:
                        p = types.SamplingParams(max_tokens=n, temperature=temperature, seed=seed,
                                                 stop=stops)
                        fut = samp.sample(prompt=types.ModelInput.from_ints(prompt_ids),
                                          num_samples=1, sampling_params=p)
                        out = list(fut.result(timeout=600).sequences[0].tokens)
                    self._count(model, billed_prompt=len(prompt_ids), billed_gen=len(out))
                    return out
                except Exception:
                    if attempt == 4:
                        raise
                    time.sleep(2 ** attempt)

        if not think:
            gen = sample(ids, max_tokens)
            return tok.decode(gen, skip_special_tokens=True).strip(), len(ids), len(gen)
        # reasoning gets its own budget; the answer always gets max_tokens on top of it
        gen = sample(ids, THINK_BUDGET[thinking] + max_tokens)
        raw = tok.decode(gen, skip_special_tokens=False)
        if "</think>" in raw:
            if not any(s in raw for s in stops) and len(gen) >= THINK_BUDGET[thinking] + max_tokens:
                # closed the reasoning late and ran out mid-answer: let the answer finish
                gen = gen + sample(ids + gen, max_tokens)
                raw = tok.decode(gen, skip_special_tokens=False)
            ans = raw.split("</think>", 1)[1]
        else:
            # budget forcing: close the reasoning and make the model answer now
            ans_ids = sample(ids + gen + list(tok.encode("\n</think>\n\n", add_special_tokens=False)),
                             max_tokens)
            gen = gen + ans_ids
            ans = tok.decode(ans_ids, skip_special_tokens=False)
        for s in stops:
            ans = ans.replace(s, "")
        return ans.strip(), len(ids), len(gen)
